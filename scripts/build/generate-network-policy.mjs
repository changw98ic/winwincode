#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'
const root = new URL('../../', import.meta.url)
const policy = JSON.parse(readFileSync(new URL('schema/winwincode/network-request-policy.json', root), 'utf8'))
assert.equal(policy.version, 'winwincode.network-request-policy.v1')
for (const key of ['maxAttempts', 'initialDelayMs', 'maxConnectionDelayMs', 'maxImmediateWaitMs', 'authorityCheckMs', 'jitterMs']) {
  assert.ok(Number.isSafeInteger(policy[key]) && policy[key] > 0, key)
}
const path = new URL('packages/network-request/src/policy.generated.mjs', root)
const source = `// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/build/generate-network-policy.mjs.\nexport const policy = Object.freeze(${JSON.stringify(policy, null, 2)})\n`
if (process.argv.includes('--check')) assert.equal(readFileSync(path, 'utf8'), source, 'network policy generation drift')
else writeFileSync(path, source)
