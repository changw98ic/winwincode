function rustFieldName(value) {
  const snake = value
    .replaceAll(/([a-z0-9])([A-Z])/gu, '$1_$2')
    .replaceAll(/[^A-Za-z0-9]+/gu, '_')
    .replaceAll(/^_+|_+$/gu, '')
    .toLowerCase() || 'field'
  const prefixed = /^[0-9]/u.test(snake) ? `field_${snake}` : snake
  return RUST_RESERVED_WORDS.has(prefixed) ? `${prefixed}_value` : prefixed
}

function rustVariantName(value, used = new Set()) {
  const base = typescriptEnumVariant(value, used)
  return RUST_RESERVED_WORDS.has(base.toLowerCase()) ? `${base}Value` : base
}

function rustPrimitiveType(type) {
  if (type === 'string') return 'String'
  if (type === 'integer') return 'i64'
  if (type === 'number') return 'f64'
  if (type === 'boolean') return 'bool'
  if (type === 'null') return '()'
  return 'serde_json::Value'
}

function isRustSharedScalarDefinition(entry) {
  const { schema } = entry
  if (schema.const !== undefined || schema.enum !== undefined) return false
  if (
    schema.$ref !== undefined
    || schema.allOf !== undefined
    || schema.oneOf !== undefined
    || schema.anyOf !== undefined
  ) return false
  const types = schemaTypes(schema)
  return types.length === 1 && ['boolean', 'integer', 'number', 'string'].includes(types[0])
}

function rustNamedType(name, context, qualifyShared) {
  return qualifyShared && context.rustSharedDefinitionNames.has(name)
    ? `winwincode_domain::${name}`
    : name
}

function rustType(schema, document, context, qualifyShared = false) {
  if (!isObject(schema)) return 'serde_json::Value'
  if (typeof schema.$ref === 'string') {
    return rustNamedType(referenceName(schema, document, context), context, qualifyShared)
  }
  if (schema.const !== undefined) return rustPrimitiveType(typeof schema.const)
  if (Array.isArray(schema.oneOf) || Array.isArray(schema.anyOf)) {
    const branches = schema.oneOf ?? schema.anyOf
    const nonNull = branches.filter(branch => !isObject(branch) || !schemaTypes(branch).includes('null'))
    if (nonNull.length === 1 && nonNull.length !== branches.length) {
      return `Option<${rustType(nonNull[0], document, context, qualifyShared)}>`
    }
    return 'serde_json::Value'
  }
  if (Array.isArray(schema.allOf)) {
    if (schema.allOf.length === 1) {
      return rustType(schema.allOf[0], document, context, qualifyShared)
    }
    return 'serde_json::Value'
  }
  const types = schemaTypes(schema)
  if (types.length > 1) {
    const nonNull = types.filter(type => type !== 'null')
    if (nonNull.length === 1 && nonNull.length !== types.length) {
      return `Option<${rustType({ ...schema, type: nonNull[0] }, document, context, qualifyShared)}>`
    }
    return 'serde_json::Value'
  }
  const [type] = types
  if (type === 'array') {
    if (Array.isArray(schema.prefixItems)) {
      const items = schema.prefixItems.map(item => (
        rustType(isObject(item) ? item : {}, document, context, qualifyShared)
      ))
      const tuple = `(${items.join(', ')}${items.length === 1 ? ',' : ''})`
      if (tuple.length <= 88) return tuple
      return `(\n        ${items.join(',\n        ')},\n    )`
    }
    return `Vec<${rustType(isObject(schema.items) ? schema.items : {}, document, context, qualifyShared)}>`
  }
  if (type === 'object' || schema.additionalProperties !== undefined || schema.properties !== undefined) {
    if (isObject(schema.additionalProperties) && Object.keys(schema.properties ?? {}).length === 0) {
      return `std::collections::BTreeMap<String, ${rustType(schema.additionalProperties, document, context, qualifyShared)}>`
    }
    return 'serde_json::Value'
  }
  return rustPrimitiveType(type)
}

function rustDocumentation(description) {
  return descriptionLines(description, '/// ')
}

function rustObjectFields(
  schema,
  document,
  context,
  existingNames = new Set(),
  qualifyShared = false,
  typeOverrides = new Map(),
) {
  const required = new Set(Array.isArray(schema.required) ? schema.required : [])
  const properties = new Map(Object.entries(schema.properties ?? {}).map(([name, propertySchema]) => [
    name,
    { schema: isObject(propertySchema) ? propertySchema : {}, document },
  ]))
  const additionalProperties = schema.additionalProperties === true
    ? true
    : isObject(schema.additionalProperties)
      ? { schema: schema.additionalProperties, document }
      : schema.additionalProperties
  return rustObjectShapeFields(
    { properties, required, additionalProperties },
    context,
    existingNames,
    qualifyShared,
    typeOverrides,
  )
}

function rustObjectShapeFields(
  shape,
  context,
  existingNames,
  qualifyShared,
  typeOverrides = new Map(),
  includeDeserializeAttributes = true,
) {
  const fields = []
  for (const [jsonName, property] of [...shape.properties.entries()]
    .sort(([left], [right]) => left.localeCompare(right))) {
    let fieldName = rustFieldName(jsonName)
    let suffix = 2
    while (existingNames.has(fieldName)) {
      fieldName = `${rustFieldName(jsonName)}_${String(suffix)}`
      suffix += 1
    }
    existingNames.add(fieldName)
    const resolvedSchema = property.schema
    let type = typeOverrides.get(jsonName)
      ?? rustType(resolvedSchema, property.document, context, qualifyShared)
    const optional = !shape.required.has(jsonName)
    if (optional && !type.startsWith('Option<')) type = `Option<${type}>`
    fields.push(...rustDocumentation(resolvedSchema.description).map(line => `    ${line}`))
    if (optional) fields.push('    #[serde(default, skip_serializing_if = "Option::is_none")]')
    else if (includeDeserializeAttributes && type.startsWith('Option<')) {
      fields.push('    #[serde(deserialize_with = "deserialize_required_nullable")]')
    }
    fields.push(`    #[serde(rename = ${JSON.stringify(jsonName)})]`)
    fields.push(`    pub ${fieldName}: ${type},`)
  }
  if (shape.additionalProperties === true || isObject(shape.additionalProperties)) {
    let fieldName = 'additional_properties'
    let suffix = 2
    while (existingNames.has(fieldName)) {
      fieldName = `additional_properties_${String(suffix)}`
      suffix += 1
    }
    const valueType = isObject(shape.additionalProperties)
      ? rustType(
          shape.additionalProperties.schema,
          shape.additionalProperties.document,
          context,
          qualifyShared,
        )
      : 'serde_json::Value'
    fields.push('    #[serde(default, flatten)]')
    fields.push(`    pub ${fieldName}: std::collections::BTreeMap<String, ${valueType}>,`)
  }
  return fields
}

function rustObjectShapeFieldNames(shape) {
  const names = []
  const existingNames = new Set()
  for (const [jsonName] of [...shape.properties.entries()]
    .sort(([left], [right]) => left.localeCompare(right))) {
    let fieldName = rustFieldName(jsonName)
    let suffix = 2
    while (existingNames.has(fieldName)) {
      fieldName = `${rustFieldName(jsonName)}_${String(suffix)}`
      suffix += 1
    }
    existingNames.add(fieldName)
    names.push(fieldName)
  }
  return names
}

function rustJsonValueConstraint(schema, accessor, sourcePath) {
  if (!isObject(schema)) {
    throw new Error(`${sourcePath}: oneOf property constraint must be an object`)
  }
  if (schema.const !== undefined) {
    if (typeof schema.const === 'string') {
      return `matches!(${accessor}, Some(serde_json::Value::String(value)) if value == ${JSON.stringify(schema.const)})`
    }
    if (typeof schema.const === 'boolean') {
      return `${accessor}.and_then(serde_json::Value::as_bool) == Some(${String(schema.const)})`
    }
    if (typeof schema.const === 'number') {
      return `${accessor}.and_then(serde_json::Value::as_f64) == Some(${String(schema.const)}f64)`
    }
    if (schema.const === null) return `${accessor}.is_some_and(serde_json::Value::is_null)`
  }
  if (typeof schema.$ref === 'string') {
    return `${accessor}.is_some_and(|value| !value.is_null())`
  }
  const types = schemaTypes(schema)
  if (types.length === 1 && types[0] === 'null') {
    return `${accessor}.is_some_and(serde_json::Value::is_null)`
  }
  if (types.length === 1 && types[0] === 'string') {
    const checks = [`let Some(value) = value.as_str() else { return false; };`]
    if (schema.minLength !== undefined) checks.push(`if value.chars().count() < ${String(schema.minLength)} { return false; }`)
    if (schema.maxLength !== undefined) checks.push(`if value.chars().count() > ${String(schema.maxLength)} { return false; }`)
    checks.push('true')
    return `${accessor}.is_some_and(|value| {\n${checks.join('\n')}\n})`
  }
  if (types.length === 1 && types[0] === 'array') {
    const checks = ['let Some(items) = value.as_array() else { return false; };']
    if (schema.minItems === 1) checks.push('if items.is_empty() { return false; }')
    else if (schema.minItems !== undefined) checks.push(`if items.len() < ${String(schema.minItems)} { return false; }`)
    if (schema.maxItems !== undefined) checks.push(`if items.len() > ${String(schema.maxItems)} { return false; }`)
    if (isObject(schema.items) && schemaTypes(schema.items).includes('string')) {
      const itemChecks = ['let Some(value) = item.as_str() else { return false; };']
      if (schema.items.minLength !== undefined) itemChecks.push(`if value.chars().count() < ${String(schema.items.minLength)} { return false; }`)
      if (schema.items.maxLength !== undefined) itemChecks.push(`if value.chars().count() > ${String(schema.items.maxLength)} { return false; }`)
      itemChecks.push('true')
      checks.push(`if !items.iter().all(|item| {\n${itemChecks.join('\n')}\n}) { return false; }`)
    }
    checks.push('true')
    return `${accessor}.is_some_and(|value| {\n${checks.join('\n')}\n})`
  }
  throw new Error(`${sourcePath}: unsupported object-level oneOf property constraint`)
}

function rustObjectOneOfBranchExpression(branch, entry, index) {
  if (!isObject(branch) || !isObject(branch.properties)) {
    throw new Error(
      `${entry.document.path}: ${entry.name} oneOf branch ${String(index + 1)} must use property constraints`,
    )
  }
  const checks = Object.entries(branch.properties).map(([name, constraint]) => (
    rustJsonValueConstraint(
      constraint,
      `value.get(${JSON.stringify(name)})`,
      `${entry.document.path}: ${entry.name}.oneOf[${String(index)}].${name}`,
    )
  ))
  return checks.length === 0 ? 'true' : checks.join(' && ')
}

function renderRustObjectWithOneOf(entry, context, qualifyShared, lines, constTypes) {
  const shape = {
    properties: new Map(Object.entries(entry.schema.properties ?? {}).map(([name, property]) => [
      name,
      { schema: isObject(property) ? property : {}, document: entry.document },
    ])),
    required: new Set(entry.schema.required ?? []),
    additionalProperties: entry.schema.additionalProperties,
  }
  const wireName = `${entry.name}Wire`
  const fieldNames = rustObjectShapeFieldNames(shape)
  lines.push('#[derive(Debug, Clone, PartialEq, serde::Serialize)]')
  lines.push(`pub struct ${entry.name} {`)
  lines.push(...rustObjectShapeFields(
    shape,
    context,
    new Set(),
    qualifyShared,
    constTypes,
    false,
  ))
  lines.push('}')
  lines.push('')
  lines.push('#[derive(serde::Serialize, serde::Deserialize)]')
  if (entry.schema.additionalProperties === false) lines.push('#[serde(deny_unknown_fields)]')
  lines.push(`struct ${wireName} {`)
  lines.push(...rustObjectShapeFields(
    shape,
    context,
    new Set(),
    qualifyShared,
    constTypes,
    true,
  ))
  lines.push('}')
  lines.push('')
  lines.push('#[rustfmt::skip]')
  lines.push(`impl ${entry.name} {`)
  lines.push(`    fn from_wire(wire: ${wireName}) -> Result<Self, String> {`)
  lines.push('        let value = serde_json::to_value(&wire)')
  lines.push(`            .map_err(|error| format!(${JSON.stringify(`${entry.name} validation failed: {error}`)}))?;`)
  lines.push('        let matching_branches = [')
  entry.schema.oneOf.forEach((branch, index) => {
    lines.push(`            ${rustObjectOneOfBranchExpression(branch, entry, index)},`)
  })
  lines.push('        ]')
  lines.push('        .into_iter()')
  lines.push('        .filter(|matches| *matches)')
  lines.push('        .count();')
  lines.push('        if matching_branches != 1 {')
  lines.push(`            return Err(${JSON.stringify(`${entry.name} must match exactly one oneOf branch`)}.to_owned());`)
  lines.push('        }')
  lines.push(`        let ${wireName} {`)
  for (const name of fieldNames) lines.push(`            ${name},`)
  lines.push('        } = wire;')
  lines.push('        Ok(Self {')
  for (const name of fieldNames) lines.push(`            ${name},`)
  lines.push('        })')
  lines.push('    }')
  lines.push('}')
  lines.push('')
  lines.push('#[rustfmt::skip]')
  lines.push(`impl<'de> serde::Deserialize<'de> for ${entry.name} {`)
  lines.push('    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>')
  lines.push('    where')
  lines.push("        D: serde::Deserializer<'de>,")
  lines.push('    {')
  lines.push(`        let wire = <${wireName} as serde::Deserialize>::deserialize(deserializer)?;`)
  lines.push('        Self::from_wire(wire).map_err(serde::de::Error::custom)')
  lines.push('    }')
  lines.push('}')
  return lines.join('\n')
}

function renderRustObject(entry, context, qualifyShared) {
  const lines = [...rustDocumentation(entry.schema.description)]
  const constTypes = new Map()
  for (const [jsonName, property] of Object.entries(entry.schema.properties ?? {})) {
    if (!isObject(property) || typeof property.const !== 'string') continue
    const typeName = `${entry.name}${rustVariantName(jsonName)}`
    constTypes.set(jsonName, typeName)
    lines.push('#[derive(Debug, Clone, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]')
    lines.push(`pub enum ${typeName} {`)
    lines.push(`    #[serde(rename = ${JSON.stringify(property.const)})]`)
    lines.push(`    ${rustVariantName(property.const)},`)
    lines.push('}')
    lines.push('')
  }
  if (Array.isArray(entry.schema.oneOf)) {
    return renderRustObjectWithOneOf(entry, context, qualifyShared, lines, constTypes)
  }
  lines.push('#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]')
  if (entry.schema.additionalProperties === false) lines.push('#[serde(deny_unknown_fields)]')
  const fields = rustObjectFields(
    entry.schema,
    entry.document,
    context,
    new Set(),
    qualifyShared,
    constTypes,
  )
  if (fields.length === 0) {
    lines.push(`pub struct ${entry.name} {}`)
    return lines.join('\n')
  }
  lines.push(`pub struct ${entry.name} {`)
  lines.push(...fields)
  lines.push('}')
  return lines.join('\n')
}

function renderRustAllOf(entry, context, qualifyShared) {
  const lines = [...rustDocumentation(entry.schema.description)]
  const shape = allOfObjectShape(entry.schema, entry.document, context)
  if (shape === undefined) {
    throw new Error(`${entry.document.path}: ${entry.name} allOf cannot generate a Rust DTO`)
  }
  const constTypes = new Map()
  for (const [jsonName, property] of shape.properties) {
    if (typeof property.schema.const !== 'string') continue
    const typeName = `${entry.name}${rustVariantName(jsonName)}`
    constTypes.set(jsonName, typeName)
    lines.push('#[derive(Debug, Clone, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]')
    lines.push(`pub enum ${typeName} {`)
    lines.push(`    #[serde(rename = ${JSON.stringify(property.schema.const)})]`)
    lines.push(`    ${rustVariantName(property.schema.const)},`)
    lines.push('}')
    lines.push('')
  }
  lines.push('#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]')
  if (shape.additionalProperties === false) lines.push('#[serde(deny_unknown_fields)]')
  lines.push(`pub struct ${entry.name} {`)
  lines.push(...rustObjectShapeFields(shape, context, new Set(), qualifyShared, constTypes))
  lines.push('}')
  return lines.join('\n')
}

function renderRustUnion(entry, context, qualifyShared) {
  const branches = entry.schema.oneOf ?? entry.schema.anyOf
  const nonNull = branches.filter(branch => !isObject(branch) || !schemaTypes(branch).includes('null'))
  if (nonNull.length === 1 && nonNull.length !== branches.length) {
    return [
      ...rustDocumentation(entry.schema.description),
      `pub type ${entry.name} = Option<${rustType(nonNull[0], entry.document, context, qualifyShared)}>;`,
    ].join('\n')
  }
  const lines = [...rustDocumentation(entry.schema.description)]
  lines.push('#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]')
  lines.push('#[serde(untagged)]')
  lines.push(`pub enum ${entry.name} {`)
  const used = new Set()
  branches.forEach((branch, index) => {
    const referenced = isObject(branch) && typeof branch.$ref === 'string'
      ? referenceName(branch, entry.document, context)
      : undefined
    const type = isObject(branch)
      ? rustType(branch, entry.document, context, qualifyShared)
      : 'serde_json::Value'
    const variant = rustVariantName(referenced ?? `Variant${String(index + 1)}`, used)
    const declaration = `    ${variant}(${type}),`
    if (declaration.length <= 100) lines.push(declaration)
    else {
      lines.push(`    ${variant}(`)
      lines.push(`        ${type},`)
      lines.push('    ),')
    }
  })
  lines.push('}')
  return lines.join('\n')
}

function renderRustDefinition(entry, context, qualifyShared) {
  const { name, schema, document } = entry
  if (typeof schema.const === 'string') {
    return [
      ...rustDocumentation(schema.description),
      '#[derive(Debug, Clone, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]',
      `pub enum ${name} {`,
      `    #[serde(rename = ${JSON.stringify(schema.const)})]`,
      `    ${rustVariantName(schema.const)},`,
      '}',
    ].join('\n')
  }
  if (
    Array.isArray(schema.enum)
    && schema.enum.length > 0
    && schema.enum.every(value => typeof value === 'string')
  ) {
    const lines = [...rustDocumentation(schema.description)]
    lines.push('#[derive(Debug, Clone, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]')
    lines.push(`pub enum ${name} {`)
    const used = new Set()
    for (const value of schema.enum) {
      lines.push(`    #[serde(rename = ${JSON.stringify(value)})]`)
      lines.push(`    ${rustVariantName(value, used)},`)
    }
    lines.push('}')
    return lines.join('\n')
  }
  if (schema.type === 'object' || schema.properties !== undefined) {
    if (isObject(schema.additionalProperties) && Object.keys(schema.properties ?? {}).length === 0) {
      return [
        ...rustDocumentation(schema.description),
        `pub type ${name} = ${rustType(schema, document, context, qualifyShared)};`,
      ].join('\n')
    }
    return renderRustObject(entry, context, qualifyShared)
  }
  if (Array.isArray(schema.allOf)) return renderRustAllOf(entry, context, qualifyShared)
  if (Array.isArray(schema.oneOf) || Array.isArray(schema.anyOf)) {
    return renderRustUnion(entry, context, qualifyShared)
  }
  return [
    ...rustDocumentation(schema.description),
    `pub type ${name} = ${rustType(schema, document, context, qualifyShared)};`,
  ].join('\n')
}

function renderRustSharedDefinition(entry) {
  const primitive = rustPrimitiveType(schemaTypes(entry.schema)[0])
  const derives = primitive === 'f64'
    ? 'Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize'
    : 'Debug, Clone, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize'
  return [
    ...rustDocumentation(entry.schema.description),
    `#[derive(${derives})]`,
    '#[serde(transparent)]',
    `pub struct ${entry.name}(pub ${primitive});`,
  ].join('\n')
}

