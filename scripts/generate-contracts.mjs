const GENERATED_MARKER = 'Generated by scripts/generate-contracts.mjs. Do not edit.'

function usage() {
  return [
    'Usage: node scripts/generate-contracts.mjs [options]',
    '',
    'Options:',
    '  --check                         Verify generated files without writing them',
    '  --schema-dir PATH               Read canonical *.schema.json files from PATH',
    '  --out-dir PATH                  Write the five fixture-style outputs below PATH',
    '  --rust-out PATH                 Override the generated Rust API module path',
    '  --rust-domain-out PATH          Override the generated shared Rust domain module path',
    '  --typescript-out PATH           Override the generated TypeScript path',
    '  --schema-collection-out PATH    Override the JSON Schema collection path',
    '  --openapi-out PATH              Override the OpenAPI document path',
    '  --help                          Print this help',
    '',
  ].join('\n')
}

function parseArguments(arguments_) {
  const options = {
    check: false,
    schemaDirectory: join(root, 'schema', 'winwincode', 'v1'),
    rustOutput: join(root, 'crates', 'winwincode-api', 'src', 'generated.rs'),
    rustDomainOutput: join(root, 'crates', 'winwincode-domain', 'src', 'generated.rs'),
    typescriptOutput: join(root, 'apps', 'web', 'src', 'generated', 'contracts.ts'),
    schemaCollectionOutput: join(
      root,
      'schema',
      'winwincode',
      'v1',
      'schema-collection.generated.json',
    ),
    openapiOutput: join(root, 'schema', 'winwincode', 'v1', 'openapi.generated.json'),
  }
  let outputDirectory

  for (let index = 0; index < arguments_.length; index += 1) {
    const argument = arguments_[index]
    if (argument === '--check') {
      options.check = true
      continue
    }
    if (argument === '--help') {
      process.stdout.write(usage())
      process.exit(0)
    }
    const valueOptions = new Map([
      ['--schema-dir', 'schemaDirectory'],
      ['--rust-out', 'rustOutput'],
      ['--rust-domain-out', 'rustDomainOutput'],
      ['--typescript-out', 'typescriptOutput'],
      ['--schema-collection-out', 'schemaCollectionOutput'],
      ['--openapi-out', 'openapiOutput'],
    ])
    if (argument === '--out-dir') {
      outputDirectory = arguments_[index + 1]
      if (outputDirectory === undefined) throw new Error('--out-dir requires a path')
      index += 1
      continue
    }
    const property = valueOptions.get(argument)
    if (property !== undefined) {
      const value = arguments_[index + 1]
      if (value === undefined) throw new Error(`${argument} requires a path`)
      options[property] = resolve(value)
      index += 1
      continue
    }
    throw new Error(`unknown argument: ${argument}`)
  }

  if (outputDirectory !== undefined) {
    const directory = resolve(outputDirectory)
    options.rustOutput = join(directory, 'rust', 'generated.rs')
    options.rustDomainOutput = join(directory, 'rust-domain', 'generated.rs')
    options.typescriptOutput = join(directory, 'typescript', 'generated.ts')
    options.schemaCollectionOutput = join(directory, 'schema-collection.generated.json')
    options.openapiOutput = join(directory, 'openapi.generated.json')
  }
  options.schemaDirectory = resolve(options.schemaDirectory)
  return options
}

function isObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
}

function canonicalValue(value) {
  if (Array.isArray(value)) return value.map(canonicalValue)
  if (!isObject(value)) return value
  return Object.fromEntries(
    Object.entries(value)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, entry]) => [key, canonicalValue(entry)]),
  )
}

function canonicalJson(value) {
  return `${JSON.stringify(canonicalValue(value), null, 2)}\n`
}

function schemaFiles(directory) {
  if (!existsSync(directory)) return []
  return readdirSync(directory, { withFileTypes: true })
    .filter(entry => entry.isFile() && entry.name.endsWith('.schema.json'))
    .map(entry => join(directory, entry.name))
    .sort((left, right) => left.localeCompare(right))
}

function loadDocuments(directory) {
  const documents = []
  const paths = schemaFiles(directory)
  for (const path of paths) {
    let schema
    try {
      schema = JSON.parse(readFileSync(path, 'utf8'))
    } catch (error) {
      throw new Error(`${path}: invalid JSON: ${error.message}`)
    }
    if (!isObject(schema)) throw new Error(`${path}: root schema must be an object`)
    if (schema.$schema !== JSON_SCHEMA_DIALECT) {
      throw new Error(`${path}: $schema must be ${JSON_SCHEMA_DIALECT}`)
    }
    if (typeof schema.$id !== 'string' || schema.$id.length === 0) {
      throw new Error(`${path}: a stable $id is required`)
    }
    if (schema.$defs !== undefined && !isObject(schema.$defs)) {
      throw new Error(`${path}: $defs must be an object`)
    }
    documents.push({
      path,
      schema,
      id: schema.$id,
      fileName: basename(path),
    })
  }
  return documents
}

function definitionRegistry(documents) {
  const registry = new Map()
  const documentByPath = new Map()
  const documentById = new Map()

  for (const document of documents) {
    const normalizedPath = resolve(document.path)
    if (documentByPath.has(normalizedPath)) throw new Error(`duplicate schema path: ${normalizedPath}`)
    if (documentById.has(document.id)) throw new Error(`duplicate schema $id: ${document.id}`)
    documentByPath.set(normalizedPath, document)
    documentById.set(document.id, document)
    documentById.set(document.id.replace(/#.*$/u, ''), document)

    for (const [name, schema] of Object.entries(document.schema.$defs ?? {})) {
      if (!/^[A-Z][A-Za-z0-9]*$/u.test(name)) {
        throw new Error(`${document.path}: $defs name must be PascalCase: ${name}`)
      }
      if (!isObject(schema)) throw new Error(`${document.path}: $defs/${name} must be an object`)
      const existing = registry.get(name)
      if (existing !== undefined) {
        throw new Error(
          `duplicate public $defs name ${name}: ${existing.document.path} and ${document.path}`,
        )
      }
      registry.set(name, { name, schema, document })
    }
  }

  return { registry, documentByPath, documentById }
}

function decodeJsonPointerSegment(value) {
  return decodeURIComponent(value).replaceAll('~1', '/').replaceAll('~0', '~')
}

function referencedDefinitionName(reference, document, context) {
  if (typeof reference !== 'string') {
    throw new Error(`${document.path}: $ref must be a string`)
  }
  const hashIndex = reference.indexOf('#')
  const documentReference = hashIndex === -1 ? reference : reference.slice(0, hashIndex)
  const fragment = hashIndex === -1 ? '' : reference.slice(hashIndex + 1)
  if (!fragment.startsWith('/$defs/')) {
    throw new Error(`${document.path}: only $defs references are supported: ${reference}`)
  }
  const name = decodeJsonPointerSegment(fragment.slice('/$defs/'.length))
  let targetDocument = document

  if (documentReference.length > 0) {
    if (/^https?:\/\//u.test(documentReference)) {
      targetDocument = context.documentById.get(documentReference)
    } else {
      targetDocument = context.documentByPath.get(
        resolve(dirname(document.path), documentReference),
      )
    }
    if (targetDocument === undefined) {
      throw new Error(`${document.path}: $ref leaves the local canonical schema set: ${reference}`)
    }
  }

  if (!Object.hasOwn(targetDocument.schema.$defs ?? {}, name)) {
    throw new Error(`${document.path}: unresolved $ref ${reference}`)
  }
  const registered = context.registry.get(name)
  if (registered?.document !== targetDocument) {
    throw new Error(`${document.path}: $ref ${reference} does not resolve to one public type`)
  }
  return name
}

function visitSchema(value, callback) {
  if (Array.isArray(value)) {
    for (const entry of value) visitSchema(entry, callback)
    return
  }
  if (!isObject(value)) return
  callback(value)
  for (const entry of Object.values(value)) visitSchema(entry, callback)
}

function constDiscriminatorValue(schema, propertyName, document, context, seen = new Set()) {
  let resolved = schema
  let sourceDocument = document
  if (typeof schema.$ref === 'string') {
    const name = referencedDefinitionName(schema.$ref, document, context)
    const entry = context.registry.get(name)
    const key = `${entry.document.id}#/$defs/${name}`
    if (seen.has(key)) return undefined
    seen.add(key)
    resolved = entry.schema
    sourceDocument = entry.document
  }
  const property = resolved.properties?.[propertyName]
  if (isObject(property) && (typeof property.const === 'string' || typeof property.const === 'number')) {
    return property.const
  }
  for (const branch of resolved.allOf ?? []) {
    if (!isObject(branch)) continue
    const value = constDiscriminatorValue(
      branch,
      propertyName,
      sourceDocument,
      context,
      new Set(seen),
    )
    if (value !== undefined) return value
  }
  return undefined
}

function validateDocuments(documents, context) {
  for (const document of documents) {
    visitSchema(document.schema, schema => {
      if (schema.$ref !== undefined) referencedDefinitionName(schema.$ref, document, context)
      if (schema.discriminator !== undefined) {
        const propertyName = schema.discriminator?.propertyName
        if (typeof propertyName !== 'string' || propertyName.length === 0) {
          throw new Error(`${document.path}: discriminator.propertyName must be a string`)
        }
        if (!Array.isArray(schema.oneOf) || schema.oneOf.length < 2) {
          throw new Error(`${document.path}: discriminated schema must contain at least two oneOf branches`)
        }
        const values = schema.oneOf.map(branch => (
          isObject(branch)
            ? constDiscriminatorValue(branch, propertyName, document, context)
            : undefined
        ))
        if (values.some(value => value === undefined) || new Set(values).size !== values.length) {
          throw new Error(
            `${document.path}: each discriminated oneOf branch must have a unique ${propertyName} const`,
          )
        }
      }
    })
  }
}

function referenceName(schema, document, context) {
  return referencedDefinitionName(schema.$ref, document, context)
}

function unique(values) {
  return [...new Set(values)]
}

function schemaTypes(schema) {
  if (Array.isArray(schema.type)) return schema.type
  return typeof schema.type === 'string' ? [schema.type] : []
}

function tsLiteral(value) {
  if (typeof value === 'string') return JSON.stringify(value)
  if (typeof value === 'number' || typeof value === 'boolean' || value === null) return String(value)
  return 'unknown'
}

function tsObjectType(schema, document, context) {
  const required = new Set(Array.isArray(schema.required) ? schema.required : [])
  const properties = Object.entries(schema.properties ?? {})
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, propertySchema]) => {
      if (!isObject(propertySchema)) return `  readonly ${JSON.stringify(name)}${required.has(name) ? '' : '?'}: unknown`
      return `  readonly ${JSON.stringify(name)}${required.has(name) ? '' : '?'}: ${tsType(propertySchema, document, context)}`
    })
  const body = properties.length === 0 ? '{}' : `{\n${properties.join('\n')}\n}`
  if (schema.additionalProperties === true) return `Readonly<Record<string, unknown>> & ${body}`
  if (isObject(schema.additionalProperties)) {
    return `Readonly<Record<string, ${tsType(schema.additionalProperties, document, context)}>> & ${body}`
  }
  return body
}

function allOfObjectShape(schema, document, context) {
  const properties = new Map()
  const required = new Set()
  let additionalProperties
  const resolving = new Set()

  function merge(node, sourceDocument) {
    if (!isObject(node)) return false
    if (typeof node.$ref === 'string') {
      const name = referenceName(node, sourceDocument, context)
      const entry = context.registry.get(name)
      if (entry === undefined) return false
      const key = `${entry.document.id}#/$defs/${name}`
      if (resolving.has(key)) {
        throw new Error(`${document.path}: recursive allOf object ${key} is not supported`)
      }
      resolving.add(key)
      const merged = merge(entry.schema, entry.document)
      resolving.delete(key)
      return merged
    }
    if (Array.isArray(node.allOf) && node.properties === undefined && node.type === undefined) {
      return node.allOf.every(branch => merge(branch, sourceDocument))
    }
    if (
      node.type !== 'object'
      && node.properties === undefined
      && node.additionalProperties === undefined
    ) return false

    for (const name of node.required ?? []) required.add(name)
    for (const [name, propertySchema] of Object.entries(node.properties ?? {})) {
      properties.set(name, {
        schema: isObject(propertySchema) ? propertySchema : {},
        document: sourceDocument,
      })
    }
    if (node.additionalProperties === false) additionalProperties = false
    else if (additionalProperties !== false && node.additionalProperties !== undefined) {
      additionalProperties = node.additionalProperties === true
        ? true
        : { schema: node.additionalProperties, document: sourceDocument }
    }
    return true
  }

  if (!merge(schema, document)) return undefined
  return { properties, required, additionalProperties }
}

function tsObjectShapeType(shape, context) {
  const properties = [...shape.properties.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, property]) => (
      `  readonly ${JSON.stringify(name)}${shape.required.has(name) ? '' : '?'}: ${tsType(property.schema, property.document, context)}`
    ))
  const body = properties.length === 0 ? '{}' : `{\n${properties.join('\n')}\n}`
  if (shape.additionalProperties === true) return `Readonly<Record<string, unknown>> & ${body}`
  if (isObject(shape.additionalProperties)) {
    return `Readonly<Record<string, ${tsType(shape.additionalProperties.schema, shape.additionalProperties.document, context)}>> & ${body}`
  }
  return body
}

function typescriptEnumMemberType(baseProperty, value, document, context) {
  if (typeof value !== 'string' && typeof value !== 'number') return undefined
  const candidates = [baseProperty, ...(baseProperty.oneOf ?? []), ...(baseProperty.anyOf ?? [])]
  for (const candidate of candidates) {
    if (!isObject(candidate) || typeof candidate.$ref !== 'string') continue
    const name = referenceName(candidate, document, context)
    const definition = context.registry.get(name)?.schema
    if (!Array.isArray(definition?.enum) || !definition.enum.includes(value)) continue
    const used = new Set()
    for (const enumValue of definition.enum) {
      const variant = typescriptEnumVariant(enumValue, used)
      if (enumValue === value) return `${name}.${variant}`
    }
  }
  return undefined
}

function tsObjectOneOfBranchType(branch, baseProperties, baseRequired, document, context) {
  if (!isObject(branch)) return 'never'
  if (branch.properties === undefined) return tsType(branch, document, context)
  const required = new Set([
    ...(branch.required ?? []),
    ...Object.keys(branch.properties).filter(name => baseRequired.has(name)),
  ])
  const properties = Object.entries(branch.properties)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, property]) => {
      const constraint = isObject(property) ? property : {}
      const baseProperty = isObject(baseProperties[name]) ? baseProperties[name] : {}
      const enumMember = constraint.const === undefined
        ? undefined
        : typescriptEnumMemberType(baseProperty, constraint.const, document, context)
      const type = enumMember ?? tsType(constraint, document, context)
      return `  readonly ${JSON.stringify(name)}${required.has(name) ? '' : '?'}: ${type}`
    })
  return properties.length === 0 ? '{}' : `{
${properties.join('\n')}
}`
}

function tsObjectOneOfType(schema, document, context) {
  const base = tsObjectType(schema, document, context)
  const baseRequired = new Set(schema.required ?? [])
  const branches = schema.oneOf.map(branch => tsObjectOneOfBranchType(
    branch,
    schema.properties ?? {},
    baseRequired,
    document,
    context,
  ))
  return `${base} & (${unique(branches).join(' | ')})`
}

function tsType(schema, document, context) {
  if (!isObject(schema)) return 'unknown'
  if (typeof schema.$ref === 'string') return referenceName(schema, document, context)
  if (schema.const !== undefined) return tsLiteral(schema.const)
  if (Array.isArray(schema.enum)) return unique(schema.enum.map(tsLiteral)).join(' | ') || 'never'
  if (
    Array.isArray(schema.oneOf)
    && (schema.type === 'object' || schema.properties !== undefined)
  ) return tsObjectOneOfType(schema, document, context)
  if (Array.isArray(schema.oneOf)) {
    return unique(schema.oneOf.map(branch => tsType(branch, document, context))).join(' | ')
  }
  if (Array.isArray(schema.anyOf)) {
    return unique(schema.anyOf.map(branch => tsType(branch, document, context))).join(' | ')
  }
  if (Array.isArray(schema.allOf)) {
    return unique(schema.allOf.map(branch => tsType(branch, document, context))).join(' & ')
  }
  const types = schemaTypes(schema)
  if (types.length > 1) {
    return unique(types.map(type => tsType({ ...schema, type }, document, context))).join(' | ')
  }
  const [type] = types
  if (type === 'string') return 'string'
  if (type === 'integer' || type === 'number') return 'number'
  if (type === 'boolean') return 'boolean'
  if (type === 'null') return 'null'
  if (type === 'array') {
    if (Array.isArray(schema.prefixItems)) {
      return `readonly [${schema.prefixItems.map(item => (
        tsType(isObject(item) ? item : {}, document, context)
      )).join(', ')}]`
    }
    return `ReadonlyArray<${tsType(isObject(schema.items) ? schema.items : {}, document, context)}>`
  }
  if (type === 'object' || schema.properties !== undefined || schema.additionalProperties !== undefined) {
    return tsObjectType(schema, document, context)
  }
  return 'unknown'
}

function descriptionLines(description, prefix) {
  if (typeof description !== 'string' || description.trim().length === 0) return []
  return description.trim().split(/\r?\n/u).map(line => `${prefix}${line.trim()}`)
}

function typescriptDocumentation(description) {
  if (typeof description !== 'string' || description.trim().length === 0) return []
  const lines = description.trim().split(/\r?\n/u).map(line => line.trim())
  if (lines.length === 1) return [`/** ${lines[0]} */`]
  return ['/**', ...lines.map(line => ` * ${line}`), ' */']
}

function typescriptEnumVariant(value, used) {
  const base = String(value)
    .split(/[^A-Za-z0-9]+/u)
    .filter(Boolean)
    .map(part => {
      const normalized = part === part.toUpperCase() ? part.toLowerCase() : part
      return `${normalized.slice(0, 1).toUpperCase()}${normalized.slice(1)}`
    })
    .join('') || 'Value'
  const prefixed = /^[0-9]/u.test(base) ? `Value${base}` : base
  let candidate = prefixed
  let suffix = 2
  while (used.has(candidate)) {
    candidate = `${prefixed}${String(suffix)}`
    suffix += 1
  }
  used.add(candidate)
  return candidate
}

function renderTypescriptDefinition(entry, context) {
  const { name, schema, document } = entry
  const lines = [...typescriptDocumentation(schema.description)]
  if (name.endsWith('Id') && schemaTypes(schema).includes('string') && schema.enum === undefined) {
    lines.push(`export type ${name} = string & { readonly __brand: ${JSON.stringify(name)} }`)
    return lines.join('\n')
  }
  if (
    Array.isArray(schema.enum)
    && schema.enum.length > 0
    && schema.enum.every(value => typeof value === 'string' || typeof value === 'number')
  ) {
    const used = new Set()
    lines.push(`export enum ${name} {`)
    for (const value of schema.enum) {
      lines.push(`  ${typescriptEnumVariant(value, used)} = ${tsLiteral(value)},`)
    }
    lines.push('}')
    return lines.join('\n')
  }
  if (Array.isArray(schema.allOf)) {
    const shape = allOfObjectShape(schema, document, context)
    if (shape !== undefined) {
      lines.push(`export type ${name} = ${tsObjectShapeType(shape, context)}`)
      return lines.join('\n')
    }
  }
  if (schema.type === 'object' || schema.properties !== undefined) {
    if (Array.isArray(schema.oneOf)) {
      lines.push(`export type ${name} = ${tsObjectOneOfType(schema, document, context)}`)
      return lines.join('\n')
    }
    if (
      isObject(schema.additionalProperties)
      && Object.keys(schema.properties ?? {}).length === 0
    ) {
      lines.push(
        `export interface ${name} extends Readonly<Record<string, ${tsType(schema.additionalProperties, document, context)}>> {}`,
      )
      return lines.join('\n')
    }
    lines.push(`export type ${name} = ${tsObjectType(schema, document, context)}`)
    return lines.join('\n')
  }
  lines.push(`export type ${name} = ${tsType(schema, document, context)}`)
  return lines.join('\n')
}

function renderTypescript(context, digest) {
  const entries = [...context.registry.values()].sort((left, right) => left.name.localeCompare(right.name))
  const declarations = entries.map(entry => renderTypescriptDefinition(entry, context))
  return [
    '// SPDX-License-Identifier: Apache-2.0',
    `// ${GENERATED_MARKER}`,
    `// Source digest: sha256:${digest}`,
    '',
    '/** Canonical Control Plane routes and projection refresh behavior for the generated Web client. */',
    `export const WINWINCODE_CLIENT_METADATA = ${JSON.stringify(context.clientMetadata, null, 2)} as const`,
    '',
    ...declarations.flatMap(declaration => [declaration, '']),
  ].join('\n')
}

